// Generates supabase/migrations/20251016000002_seed.sql from the template
// catalog: languages, categories, publications, and empty reporting periods
// (Mar 2024 onward). No quantities — the owner imports those via the app.
// Run: node scripts/generate-seed.mjs
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
// Template module is dependency-free, so plain execution works.
const template = await import(join(root, "src/lib/reports/template.ts"));
const { CATALOG, SECTIONS, MONTH_GROUPS } = template;

const sqlEscape = (s) => `'${String(s).replace(/'/g, "''")}'`;
const out = [];
out.push("-- Structural seed: catalog + empty reporting periods. No quantities.");
out.push("-- Generated by scripts/generate-seed.mjs — do not hand-edit; re-run.");
out.push("");
out.push(`insert into public.languages (code, label) values ('en', 'English'), ('tl', 'Tagalog') on conflict (code) do nothing;`);
out.push("");

for (const lang of ["en", "tl"]) {
  SECTIONS.forEach((name, i) => {
    out.push(
      `insert into public.publication_categories (language_code, name, sort_order) values ('${lang}', ${sqlEscape(name)}, ${i}) on conflict (language_code, name) do nothing;`,
    );
  });
}
out.push("");

// Periods Mar 2024 through Aug 2032 (order 0..16), six month slots each.
const pad = (n) => String(n).padStart(2, "0");
const ym = (y, m) => `${y}-${pad(m + 1)}-01`;
for (let order = 0; order <= 16; order++) {
  const even = order % 2 === 0;
  const year = 2024 + Math.floor(order / 2);
  const key = even ? `${year}-mar-aug` : `${year}-sep-feb`;
  const label = even ? `Mar – Aug ${year}` : `Sep ${year} – Feb ${year + 1}`;
  const startMonth = even ? 2 : 8;
  const startYear = year;
  const first = ym(startYear, startMonth);
  // end = start + 6 months (exclusive upper bound stored as end_month)
  const endTotal = startYear * 12 + startMonth + 6;
  const last = ym(Math.floor(endTotal / 12), endTotal % 12);
  out.push(
    `insert into public.reporting_periods (key, label, start_month, end_month) values (${sqlEscape(key)}, ${sqlEscape(label)}, '${first}', '${last}') on conflict (key) do nothing;`,
  );
  const pairFor = (i) => MONTH_GROUPS[i];
  for (let i = 0; i < 6; i++) {
    const total = startYear * 12 + startMonth + i;
    const my = ym(Math.floor(total / 12), total % 12);
    out.push(
      `insert into public.reporting_months (period_id, month, position, pair_label) values ((select id from public.reporting_periods where key = ${sqlEscape(key)}), '${my}', ${i + 1}, ${sqlEscape(pairFor(i))}) on conflict (period_id, position) do nothing;`,
    );
  }
}
out.push("");

// Publications per language (same template both sides until localized).
let sort = 0;
for (const lang of ["en", "tl"]) {
  for (const r of CATALOG) {
    sort += 1;
    out.push(
      `insert into public.publications (language_code, category_id, item_no, name, code, sort_order) values ('${lang}', (select id from public.publication_categories where language_code = '${lang}' and name = ${sqlEscape(r.section)}), ${r.itemNo === null ? "null" : sqlEscape(r.itemNo)}, ${sqlEscape(r.name)}, ${r.code === null ? "null" : sqlEscape(r.code)}, ${sort}) on conflict do nothing;`,
    );
  }
}

const target = join(root, "supabase/migrations/20251016000002_seed.sql");
writeFileSync(target, out.join("\n") + "\n");
console.log(`wrote ${target} (${out.length} statements)`);
